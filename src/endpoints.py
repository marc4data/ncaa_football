PER_GAME_COST_NOTE = """
Per-game endpoints fan out to one call per game. At ~3,800 completed games per season,
each PER_GAME endpoint costs ~3,800 calls per season — roughly 7,600 per season for both,
15,000 for 2024+2025. That fits a 75,000/month Tier 3 quota but is a different order of
magnitude from the ~600-call bulk sweep, so it is opt-in:

    python -m src.backfill --per-game --seasons 2024
""".strip()

BY_PATH: Dict[str, Endpoint] = {e.path: e for e in REGISTRY}
SWEEPABLE = [e for e in REGISTRY if e.include]


def by_strategy(strategy: str) -> List[Endpoint]:
    return [e for e in REGISTRY if e.strategy == strategy]


def resolve(names: List[str]) -> List[Endpoint]:
    """Look endpoints up by path, raising on anything unknown."""
    unknown = [n for n in names if n not in BY_PATH]
    if unknown:
        raise KeyError(f"unknown endpoint(s): {', '.join(unknown)}")
    return [BY_PATH[n] for n in names]
