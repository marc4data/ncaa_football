"""Registry of every CFBD endpoint, and how to fetch it.

Generated by hand from the CFBD OpenAPI spec (v5.24.0, 74 paths) and corrected by probing
the live API. This is the single place that decides *what exists* and *how it is
parameterized*; `src/backfill.py` executes it and knows nothing about individual endpoints.

Strategies
----------
STATIC        no parameters — one call, ever (reference data)
SEASON        one call per season: {year}
SEASON_TYPE   one call per (season, seasonType) — data that splits regular/postseason
SEASON_WEEK   one call per (season, seasonType, week) — the volume drivers
PER_GAME      one call per game id; fan-out is large, opt-in only
MANUAL        needs an argument no backfill can invent (a search term, a player id,
              a specific matchup) — reachable via `src.ingest`, never swept
LIVE          only meaningful during a game in progress; never backfilled

`include` marks membership of the default full-breadth sweep. PER_GAME/MANUAL/LIVE are
excluded by default and opted into explicitly, because their cost is a different order of
magnitude (see PER_GAME_COST_NOTE).
"""
from dataclasses import dataclass, field
from typing import Dict, List

STATIC = "static"
SEASON = "season"
SEASON_TYPE = "season_type"
SEASON_WEEK = "season_week"
PER_GAME = "per_game"
MANUAL = "manual"
LIVE = "live"

# Cadence buckets from the roadmap's M1 classification.
BUCKET_STRUCTURAL = "A"      # season-scoped structural facts
BUCKET_HISTORICAL = "B"      # immutable once the season completes
BUCKET_REVISIONIST = "C1"    # revises retroactively; re-pull whole current season
BUCKET_IMMUTABLE_WK = "C2"   # immutable once the week completes
BUCKET_PREGAME = "D"         # time-sensitive, pre-game
BUCKET_REFERENCE = "REF"     # static lookups


@dataclass(frozen=True)
class Endpoint:
    path: str
    strategy: str
    bucket: str
    include: bool = True
    note: str = ""
    # Snapshot endpoints answer differently to the *same* request over time — betting
    # lines move, pre-game win probability shifts. For these, repeat fetches with
    # identical params are the point, so `--snapshot` bypasses skip-if-present. Without
    # this the daily lines pull would be skipped from its second run onward and the
    # movement series would never accumulate.
    snapshot: bool = False
    extra: Dict[str, str] = field(default_factory=dict)

    @property
    def key(self) -> str:
        """Directory / manifest key — mirrors src.ingest."""
        return self.path.replace("/", "_")


